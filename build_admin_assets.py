#!/usr/bin/env python3
"""Regenerate the ADMIN_HTML / ADMIN_CSS / ADMIN_JS constants inside
index.js from the editable sources in admin_src/.

Run after editing anything in admin_src/:
    python3 build_admin_assets.py
The generated block sits between the ADMIN ASSETS BEGIN/END markers in
index.js. The strings are JSON-encoded, so any content is safe.
"""
import io
import json
import re
import sys

BEGIN = "// === ADMIN ASSETS BEGIN"
END = "// === ADMIN ASSETS END ==="


def main() -> int:
    with io.open("admin_src/admin.html", encoding="utf-8") as f:
        html = f.read()
    with io.open("admin_src/admin.css", encoding="utf-8") as f:
        css = f.read()
    with io.open("admin_src/admin.js", encoding="utf-8") as f:
        js = f.read()

    block = (
        BEGIN + " (generated by build_admin_assets.py from admin_src/ - do not edit by hand) ===\n"
        + "const ADMIN_HTML = " + json.dumps(html) + ";\n"
        + "const ADMIN_CSS = " + json.dumps(css) + ";\n"
        + "const ADMIN_JS = " + json.dumps(js) + ";\n"
        + END
    )

    with io.open("index.js", encoding="utf-8") as f:
        src = f.read()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(src):
        print("ERROR: ADMIN ASSETS markers not found in index.js", file=sys.stderr)
        return 1
    src = pattern.sub(lambda _m: block, src, count=1)
    with io.open("index.js", "w", encoding="utf-8") as f:
        f.write(src)
    print(f"assets embedded: html={len(html)}B css={len(css)}B js={len(js)}B")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
